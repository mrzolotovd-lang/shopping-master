def get_stock_level(text: str) -> float | None:
    """Get stock level from text."""
    text = text.lower().strip()
    for key, value in STOCK_LEVELS.items():
        if key in text:
            return value
    return None


def normalize_unit(unit: str) -> str:
    """Normalize unit to standard form."""
    return UNIT_ALIASES.get(unit.lower(), unit)


def resolve_category(category_text: str) -> str:
    """Resolve category alias to full name."""
    return CATEGORY_ALIASES.get(category_text.lower(), category_text)


def normalize_item_name(item_name: str) -> str:
    """Normalize item name using Russian normalizer."""
    return RussianNormalizer.normalize_word(item_name)
